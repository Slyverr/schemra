export type StudioMessageId = keyof typeof englishMessages;
export type StudioMessageValues = Record<string, string | number>;

export function studioMessage(id: StudioMessageId, values: StudioMessageValues = {}) {
	return Object.entries(values).reduce(
		(message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
		englishMessages[id] as string
	);
}
